import {expect, test, type Page} from '@playwright/test'
import {readFile} from 'node:fs/promises'
import {decode, editText, linkedAnchors} from '../src/model'
const example = JSON.parse(await readFile(new URL('../examples/a-quiet-interval.json', import.meta.url), 'utf8'))

const textField = (page: Page) => page.locator('#beat-text')
const pixels = (page: Page) => page.locator('#full-preview canvas').evaluate(node => (node as HTMLCanvasElement).toDataURL())
async function scrub(page: Page, value: number) {
  await page.getByRole('slider', {name: 'Scrub time'}).evaluate((node, seconds) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(node, String(seconds))
    node.dispatchEvent(new Event('input', {bubbles: true}))
  }, value)
  await expect(page.locator('.timecode')).toContainText(value.toFixed(1) + 's')
}

test('validates documents and maps emphasis across Unicode edits', () => {
  const doc = decode(example)
  const prior = {...doc.beats[0], text: '👩🏽‍🚀 é ночь', emphasis: [{id: 'emoji', start: 0, end: '👩🏽‍🚀'.length, role: 'Anchor' as const}]}
  const moved = editText(prior, '🟠 ' + prior.text)
  expect(moved.text.slice(moved.emphasis[0].start, moved.emphasis[0].end)).toBe('👩🏽‍🚀')
  expect(editText(prior, '👩‍🚀 é ночь').emphasis).toEqual([])
  expect(() => decode({...doc, beats: [{...prior, emphasis: [{...prior.emphasis[0], end: 2}]}]})).toThrow()
  expect(() => decode({...doc, beats: []})).toThrow()
  expect(() => decode({...doc, documentVersion: 2})).toThrow()
  expect(linkedAnchors(prior, doc.beats[1])).toBeUndefined()
})

test('edits, marks, mutates, reorders and restores beats', async ({page}) => {
  await page.goto('/')
  await textField(page).fill('Текст 👩🏽‍🚀 moves.\nAnother line.')
  await textField(page).press('Control+Home')
  for (let i = 0; i < 5; i++) await textField(page).press('Shift+ArrowRight')
  await page.getByRole('button', {name: 'Strong', exact: true}).click()
  await expect(page.getByRole('button', {name: 'Remove emphasis Текст'})).toBeVisible()
  await page.getByRole('button', {name: 'Mutate'}).click()
  await expect(textField(page)).toHaveValue('Текст 👩🏽‍🚀 moves.\nAnother line.')
  await expect(page.getByRole('button', {name: 'Remove emphasis Текст'})).toBeVisible()
  await page.getByRole('button', {name: 'Add beat'}).click()
  await textField(page).fill('A new beat.')
  await page.getByRole('button', {name: 'Move beat earlier'}).click()
  await expect(page.locator('.beat-card').nth(1)).toContainText('A new beat.')
  await page.getByRole('button', {name: 'Undo', exact: true}).click()
  await expect(page.locator('.beat-card').nth(2)).toContainText('A new beat.')
  await page.getByRole('button', {name: 'Redo', exact: true}).click()
  await expect(page.locator('.beat-card').nth(1)).toContainText('A new beat.')
  await page.getByRole('button', {name: 'Keep', exact: true}).click()
  await page.reload()
  await expect(page.locator('.beat-card').nth(1)).toContainText('A new beat.')
  await page.getByRole('button', {name: 'После дождя'}).click()
  await page.getByRole('button', {name: 'Collection', exact: true}).click()
  await page.locator('.collection-popover').getByRole('button', {name: 'A Quiet Interval'}).click()
  await expect(page.locator('.beat-card').nth(1)).toContainText('A new beat.')
})

test('plays, pauses, restarts and reproduces a frame across seek orders', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button', {name: 'The Returning Tide'}).click()
  await page.getByRole('button', {name: 'Compose', exact: true}).click()
  await scrub(page, 5.6)
  const transition = await pixels(page)
  await scrub(page, 6)
  expect(await pixels(page)).not.toBe(transition)
  await scrub(page, 0)
  await scrub(page, 5.6)
  expect(await pixels(page)).toBe(transition)
  await page.getByRole('button', {name: 'Play', exact: true}).click()
  await expect(page.locator('.timecode')).not.toContainText('5.6s')
  await page.getByRole('button', {name: 'Restart'}).click()
  await expect(page.locator('.timecode')).toContainText(/^0\.[0-9]s/)
  await page.getByRole('button', {name: 'Pause', exact: true}).click()
  await expect(page.getByRole('button', {name: 'Play', exact: true})).toBeVisible()
  await scrub(page, 11.9)
  await page.getByRole('button', {name: 'Loop', exact: true}).click()
  await page.getByRole('button', {name: 'Play', exact: true}).click()
  await expect(page.locator('.timecode')).toContainText(/^0\.[0-9]s/)
  await page.getByRole('button', {name: 'Pause', exact: true}).click()
})

test('imports JSON, protects a corrupt draft and exports a full-resolution PNG', async ({page}) => {
  await page.addInitScript(() => {
    if (!localStorage.getItem('textlab:draft:v1')) localStorage.setItem('textlab:draft:v1', '{invalid')
  })
  await page.goto('/')
  await expect(page.locator('.toast')).toContainText('draft could not be read')
  const file = page.getByLabel('Import document')
  await file.setInputFiles({name: 'broken.json', mimeType: 'application/json', buffer: Buffer.from('{}')})
  await expect(page.locator('.toast')).toContainText('Invalid Text Lab')
  await file.setInputFiles({name: 'valid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({...example, title: 'Imported'}))})
  await expect(page.locator('#composition-title')).toHaveValue('Imported')
  expect(await page.evaluate(() => localStorage.getItem('textlab:draft:v1:recovery'))).toBe('{invalid')
  await page.getByRole('button', {name: 'Export', exact: true}).click()
  const [png] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', {name: 'Export current PNG'}).click()])
  const image = await readFile((await png.path())!)
  expect(image.readUInt32BE(16)).toBe(1080)
  expect(image.readUInt32BE(20)).toBe(1920)
  await page.getByRole('button', {name: 'Export', exact: true}).click()
  const [json] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', {name: 'Export JSON'}).click()])
  expect(decode(JSON.parse(await readFile((await json.path())!, 'utf8'))).title).toBe('Imported')
})

test('mobile has no page overflow with all demos, long words or very short text', async ({page}) => {
  await page.setViewportSize({width: 375, height: 812})
  await page.goto('/')
  for (const title of ['A Quiet Interval', 'После дождя', 'The Returning Tide']) {
    await page.getByRole('button', {name: title, exact: true}).click()
    await expect(page.locator('#composition-title')).toHaveValue(title)
    await expect(page.locator('.live-preview canvas')).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
  }
  await textField(page).fill(('Оченьдлинноеслово'.repeat(12) + ' 👩🏽‍🚀\n').repeat(12))
  await expect(page.locator('.live-preview canvas')).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(375)
  await textField(page).fill('Да.')
  await page.getByRole('button', {name: 'Compose', exact: true}).click()
  await expect(page.locator('#full-preview canvas')).toHaveAttribute('aria-label', 'Да.')
})
