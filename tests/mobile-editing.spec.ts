import {expect, test, type Locator, type Page} from '@playwright/test'

const paragraph = 'Первый абзац. Волны тихо приближаются к берегу.\n\nВторой абзац. Вода оставляет след на песке.\n\nТретий абзац. К вечеру берег снова пуст.'
const beatText = (page: Page) => page.locator('#beat-text')
const compact = (page: Page) => page.locator('.compact-preview canvas')
const full = (page: Page) => page.locator('#full-preview canvas')
const pixels = (canvas: Locator) => canvas.evaluate(node => (node as HTMLCanvasElement).toDataURL())
const pageWidth = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth)
const viewButton = (page: Page, name: 'Edit' | 'Preview') =>
  page.getByRole('navigation', {name: 'Workspace view'}).getByRole('button', {name, exact: true})
async function scrub(page: Page, time: number) {
  await page.getByRole('slider', {name: 'Scrub time'}).evaluate((node, seconds) => {
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value')!.set!.call(node, String(seconds))
    node.dispatchEvent(new Event('input', {bubbles: true}))
  }, time)
  await expect(page.locator('.timecode')).toContainText(time.toFixed(1) + 's')
}

for (const [width, height] of [[320, 568], [375, 812], [390, 844], [428, 926]]) {
  test.describe(`mobile ${width}px`, () => {
    test.use({viewport: {width, height}, isMobile: true, hasTouch: true})
    test('opens directly in Edit and supports typing in a reduced keyboard viewport', async ({page}) => {
      await page.goto('/')
      await expect(viewButton(page, 'Edit')).toHaveAttribute('aria-pressed', 'true')
      await expect(full(page)).toBeHidden()
      await expect(compact(page)).toBeVisible()
      const mutate = await page.getByRole('button', {name: 'Mutate'}).boundingBox()
      const compactButton = await page.getByRole('button', {name: 'Open full Preview'}).boundingBox()
      expect(mutate!.x + mutate!.width).toBeLessThan(compactButton!.x)
      const field = beatText(page)
      await expect(field).toBeInViewport({ratio: 0.45})
      expect(await pageWidth(page)).toBe(width)
      expect(await field.evaluate(node => parseFloat(getComputedStyle(node).fontSize))).toBeGreaterThanOrEqual(16)
      await field.tap()
      await expect(field).toBeFocused()

      // A reduced viewport exercises reflow around a keyboard without claiming to launch iOS Safari's native keyboard.
      await page.setViewportSize({width, height: Math.round(height * 0.61)})
      await field.fill(paragraph)
      await field.press('End')
      await page.keyboard.insertText(' Тихо.')
      await expect(field).toBeFocused()
      await expect(field).toHaveValue(paragraph + ' Тихо.')
      expect(await field.evaluate(node => (node as HTMLTextAreaElement).selectionStart)).toBe(paragraph.length + 6)
      expect(await pageWidth(page)).toBe(width)

      await page.setViewportSize({width, height})
      await viewButton(page, 'Preview').tap()
      await expect(viewButton(page, 'Preview')).toHaveAttribute('aria-pressed', 'true')
      await expect(field).toBeHidden()
      const box = await full(page).boundingBox()
      expect(box!.width / box!.height).toBeCloseTo(9 / 16, 2)
      expect(box!.width).toBeGreaterThan(width * 0.53)
      await expect(page.getByRole('slider', {name: 'Scrub time'})).toBeVisible()
      expect(await pageWidth(page)).toBe(width)
      await page.getByRole('button', {name: 'Back to Edit'}).tap()
      await expect(field).toHaveValue(paragraph + ' Тихо.')
    })
  })
}

test.describe('mobile editor and transport', () => {
  test.use({viewport: {width: 390, height: 844}, isMobile: true, hasTouch: true})

  test('updates the actual selected-beat frame and restores scroll, selection and draft', async ({page}) => {
    await page.goto('/')
    const field = beatText(page)
    const originalPixels = await pixels(compact(page))
    const passage = Array.from({length: 5}, () => paragraph).join('\n\n')
    await field.fill(passage)
    const editedPixels = await pixels(compact(page))
    expect(editedPixels).not.toBe(originalPixels)
    await field.press('Control+Home')
    await field.press('Shift+ArrowRight')
    await page.getByRole('button', {name: 'Strong', exact: true}).tap()
    const markedPixels = await pixels(compact(page))
    expect(markedPixels).not.toBe(editedPixels)
    await page.getByRole('button', {name: 'Night ink'}).tap()
    expect(await pixels(compact(page))).not.toBe(markedPixels)
    await page.getByRole('button', {name: 'Undo', exact: true}).tap()
    expect(await pixels(compact(page))).toBe(markedPixels)
    await page.getByRole('button', {name: 'Redo', exact: true}).tap()

    await field.press('Control+Home')
    await field.press('Shift+ArrowRight')
    const fieldScroll = await field.evaluate(node => {
      node.scrollTop = 60
      return node.scrollTop
    })
    expect(fieldScroll).toBeGreaterThan(0)
    await page.evaluate(() => scrollTo(0, 230))
    const priorScroll = await page.evaluate(() => scrollY)
    expect(priorScroll).toBeGreaterThan(100)
    const before = await pixels(compact(page))
    await viewButton(page, 'Preview').tap()
    expect(await pixels(full(page))).toBe(before)
    expect(await page.evaluate(() => scrollY)).toBe(0)
    await page.getByRole('button', {name: 'Back to Edit'}).tap()
    expect(await page.evaluate(() => scrollY)).toBe(priorScroll)
    expect(await field.evaluate((node: HTMLTextAreaElement) => [node.selectionStart, node.selectionEnd])).toEqual([0, 1])
    expect(await field.evaluate(node => node.scrollTop)).toBe(fieldScroll)
    await expect(page.getByRole('button', {name: 'Strong', exact: true})).toBeEnabled()
    await expect(field).toHaveValue(passage)
    await page.reload()
    await expect(field).toHaveValue(passage)
  })

  test('preserves the Tide transition and pauses without resetting time when returning to Edit', async ({page}) => {
    await page.goto('/')
    await page.getByRole('button', {name: 'The Returning Tide', exact: true}).tap()
    await expect(page.getByRole('button', {name: 'Persist', exact: true})).toHaveAttribute('aria-pressed', 'true')
    await expect(page.getByLabel('Link anchor ranges')).toHaveValue(/tide-in.*tide-out/)
    await page.getByRole('button', {name: 'Open full Preview'}).tap()
    await scrub(page, 5.6)
    const transition = await pixels(full(page))
    await page.getByRole('button', {name: 'Back to Edit'}).tap()
    expect(await pixels(compact(page))).toBe(transition)
    await viewButton(page, 'Preview').tap()
    await expect(page.locator('.timecode')).toContainText('5.6s')
    expect(await pixels(full(page))).toBe(transition)
    await page.getByRole('button', {name: 'Next beat'}).tap()
    await expect(page.locator('.timecode')).toContainText('6.0s')
    await page.getByRole('button', {name: 'Play', exact: true}).tap()
    await expect(page.locator('.timecode')).not.toContainText('6.0s')
    await page.getByRole('button', {name: 'Back to Edit'}).tap()
    await expect(page.locator('.beat-card').nth(1)).toHaveAttribute('aria-pressed', 'true')
    const paused = await pixels(compact(page))
    await viewButton(page, 'Preview').tap()
    await expect(page.getByRole('button', {name: 'Play', exact: true})).toBeVisible()
    expect(await pixels(full(page))).toBe(paused)
    await page.getByRole('button', {name: 'Back to Edit'}).tap()
    await page.locator('.beat-card').nth(0).tap()
    await page.getByRole('button', {name: 'Open full Preview'}).tap()
    await expect(page.locator('.timecode')).toContainText('0.0s')
  })
})

test('keeps the sticky two-column desktop workspace', async ({page}) => {
  await page.setViewportSize({width: 1440, height: 900})
  await page.goto('/')
  await expect(viewButton(page, 'Edit')).toBeHidden()
  await expect(beatText(page)).toBeVisible()
  await expect(full(page)).toBeVisible()
  await expect(compact(page)).toHaveCount(0)
  const preview = page.getByRole('region', {name: 'Preview'})
  expect(await preview.evaluate(node => getComputedStyle(node).position)).toBe('sticky')
  expect((await preview.boundingBox())!.x).toBeLessThan((await beatText(page).boundingBox())!.x)
})
